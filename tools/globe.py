#!/usr/bin/env python3
"""Builds _includes/globe.html: a small spinning globe (the continents slide behind a round window, shaded as a sphere).
Used while the giving note is being sent. Needs geopandas<1.0.   python3 tools/globe.py"""
import warnings; warnings.filterwarnings('ignore')
import geopandas as gpd
W, H = 240, 120  # one turn of the earth = 240 units, so the 120-unit window shows half of it, as a real globe does
land = gpd.read_file(gpd.datasets.get_path('naturalearth_lowres'))
land = land[land.name != 'Antarctica'].dissolve().simplify(1.6).iloc[0]
xy = lambda lon, lat: ((lon + 180) / 360 * W, (90 - lat) / 180 * H)
d = ' '.join('M' + ' L'.join('%.1f,%.1f' % xy(*c) for c in p.exterior.coords) + 'Z' for p in land.geoms if p.area > 6)
cx, cy = xy(-71.97, -13.53)  # Cusco
# where each kind of giver flies in from: north of Peru, the United States, and over the Atlantic (Europe and beyond)
ROUTES = {'pe': (xy(-80.6, -5.2), (-3, -5)), 'us': (xy(-96, 39), (14, 2)), 'world': ((119, 34), (4, -22))}
routes = ''
for k, ((x, y), (bx, by)) in ROUTES.items():
    path = f'M{x:.1f},{y:.1f} Q{(x + cx) / 2 + bx:.1f},{(y + cy) / 2 + by:.1f} {cx:.1f},{cy:.1f}'
    routes += (f'<g class="globe__route" data-from="{k}"><path class="globe__trail" pathLength="1" d="{path}"/>'
               f'<path class="globe__plane" d="M-3,-2.4 L4,0 L-3,2.4 L-1.6,0Z"><animateMotion dur="4.5s" repeatCount="indefinite" rotate="auto" calcMode="spline" keyPoints="0;1;1" keyTimes="0;.8;1" keySplines=".4 0 .3 1;0 0 1 1" path="{path}"/></path></g>')
open('_includes/globe.html', 'w').write(f"""<!-- generated by tools/globe.py -->
<svg class="globe" viewBox="0 0 {H} {H}" aria-hidden="true">
  <defs>
    <clipPath id="globeClip"><circle cx="{H/2:.0f}" cy="{H/2:.0f}" r="{H/2 - 2:.0f}"/></clipPath>
    <radialGradient id="globeShade" cx=".36" cy=".3" r=".8"><stop offset="0" stop-color="#fff" stop-opacity=".28"/><stop offset=".55" stop-color="#fff" stop-opacity="0"/><stop offset="1" stop-color="#000" stop-opacity=".34"/></radialGradient>
  </defs>
  <circle class="globe__sea" cx="{H/2:.0f}" cy="{H/2:.0f}" r="{H/2 - 2:.0f}"/>
  <g clip-path="url(#globeClip)"><g class="globe__world" style="transform-origin:{cx:.1f}px {cy:.1f}px">
    <path class="globe__land" d="{d}"/>
    {routes}
    <circle class="globe__ping" cx="{cx:.1f}" cy="{cy:.1f}" r="2"/><circle class="globe__cusco" cx="{cx:.1f}" cy="{cy:.1f}" r="2"/>
  </g></g>
  <circle cx="{H/2:.0f}" cy="{H/2:.0f}" r="{H/2 - 2:.0f}" fill="url(#globeShade)"/>
</svg>
""")
print(len(d), 'bytes of land; Cusco at', round(cx, 1), round(cy, 1))
